-- Revisión periódica con calendario y contexto propios del grupo. Las evaluaciones anteriores conservan su alcance.
BEGIN;

CREATE TABLE "KomainOS".revision_periodica_grupo (
    id_revision_periodica_grupo integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_grupo_mantenimiento integer NOT NULL,
    fecha_inicio timestamp(0) without time zone NOT NULL,
    CONSTRAINT fk_revision_periodica_grupo_grupo FOREIGN KEY (id_grupo_mantenimiento)
        REFERENCES "KomainOS".grupo_mantenimiento(id_grupo_mantenimiento) ON UPDATE RESTRICT ON DELETE RESTRICT
);

ALTER TABLE "KomainOS".evaluacion
    ADD COLUMN id_revision_periodica_grupo integer,
    ADD CONSTRAINT fk_evaluacion_revision_grupo FOREIGN KEY (id_revision_periodica_grupo)
        REFERENCES "KomainOS".revision_periodica_grupo(id_revision_periodica_grupo) ON UPDATE RESTRICT ON DELETE RESTRICT,
    ADD CONSTRAINT ck_evaluacion_revision_grupo_tipo CHECK (id_revision_periodica_grupo IS NULL OR tipo = 'REVISION_PERIODICA');

CREATE INDEX ix_revision_periodica_grupo_fecha ON "KomainOS".revision_periodica_grupo (id_grupo_mantenimiento, fecha_inicio DESC);
CREATE UNIQUE INDEX uq_evaluacion_revision_grupo_servidor ON "KomainOS".evaluacion (id_revision_periodica_grupo, id_servidor)
    WHERE id_revision_periodica_grupo IS NOT NULL;
CREATE INDEX ix_evaluacion_servidor_fecha_sin_revision_grupal ON "KomainOS".evaluacion (id_servidor, fecha_inicio DESC)
    WHERE id_revision_periodica_grupo IS NULL;

COMMIT;
